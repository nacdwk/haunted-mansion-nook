function flatMat(c) { return new THREE.MeshStandardMaterial({ color: c, roughness: 0.92, flatShading: true }); }

// helper: textured plane (portrait etc.) material, unlit-ish so paintings read clearly
export function paintingMat(map, { ei = 0.18 } = {}) {
  const m = new THREE.MeshStandardMaterial({ map, roughness: 0.55, emissiveMap: map, emissive: 0xffffff, emissiveIntensity: ei });
  return m;
}
